  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_programs_image FOREIGN KEY (image_id) REFERENCES media_assets(id) ON DELETE SET NULL
